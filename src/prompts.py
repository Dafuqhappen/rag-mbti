"""Промпты для генерации. Вынесены отдельно — это такая же ручка качества,
как чанкинг или вес слияния, и её точно так же нужно уметь сравнивать.

Держим несколько вариантов рядом, чтобы замерить разницу, а не спорить о ней.
"""

# Строгий вариант: заземление (grounding) на контекст + разрешение
# признать незнание. Без последнего пункта модель почти всегда что-то
# выдумывает: сказать "не знаю" ей психологически "дороже", чем угадать.
STRICT_SYSTEM = """Ты — справочник по соционике (16 типов, Модель А).

Правила, которым ты обязан следовать:
1. Отвечай ТОЛЬКО на основе предоставленных источников. Не добавляй факты
   из своих общих знаний, даже если уверен в них.
2. Если в источниках нет ответа — так и скажи: "В моей базе нет данных по
   этому вопросу". Не придумывай и не догадывайся.
3. После каждого утверждения указывай номер источника в квадратных скобках,
   например: Дон Кихот — интуитивно-логический экстраверт [1].
4. Отвечай кратко и по делу, на русском языке.
5. Не пересказывай источник целиком — бери только то, что относится к вопросу."""

# Наивный вариант — то, как промпт пишет большинство новичков: без заземления
# и без права на незнание. Нужен как точка отсчёта для замера faithfulness.
LOOSE_SYSTEM = """Ты — эксперт по соционике. Отвечай на вопросы пользователя,
используя предоставленную информацию. Отвечай на русском языке."""

SYSTEM_PROMPTS = {"strict": STRICT_SYSTEM, "loose": LOOSE_SYSTEM}


def _format_hit(index: int, hit: dict) -> str:
    """Один источник: сначала найденный фрагмент, затем полное описание.

    Зачем фрагмент отдельно: при small-to-big ретривал точно знает, какой
    кусок ответил на вопрос ("болевая функция"), но наружу отдаётся весь тип
    со всеми восемью функциями. Без указателя модель выбирает строку наугад —
    и берёт соседнюю. Фрагмент возвращает ей найденное ретривалом знание.
    """
    block = f"[{index}] {hit['name']}"
    fragment = hit.get("matched_text")
    if fragment and hit.get("matched_slot") not in ("", "profile"):
        block += f"\nНаиболее релевантный фрагмент: {fragment}"
    return f"{block}\nПолное описание:\n{hit['document']}"


def format_context(hits: list[dict]) -> str:
    """Собирает найденные документы в пронумерованный блок источников.

    Нумерация нужна для ссылок [1], [2] — без неё модель не может сослаться
    на конкретный источник, и проверить её ответ становится невозможно.
    """
    return "\n\n".join(
        _format_hit(i, hit) for i, hit in enumerate(hits, start=1)
    )


def build_user_message(question: str, hits: list[dict]) -> str:
    """Складывает контекст и вопрос в одно сообщение.

    Порядок важен: сначала источники, потом вопрос. Так вопрос оказывается
    ближе к концу промпта, и модель реже "забывает" о нём на длинном контексте.
    """
    return (
        f"Источники:\n\n{format_context(hits)}\n\n"
        f"---\n\nВопрос: {question}"
    )
