"""Разбор запроса: понять, структурный ли он, и собрать metadata-фильтр.

Зачем: запросы вида «интуитивный логик экстраверт рационал» векторным поиском
не решаются в принципе — вектор умеет в похожесть, но не в булеву логику.
Для них нужен точный фильтр по metadata. Но чтобы его применить, систему
надо научить РАСПОЗНАВАТЬ такие запросы. Это и есть query understanding.

Подход: просим LLM вернуть JSON с четырьмя признаками. Три принципа реализации:

1. Structured output (json_mode) — модель физически не может вернуть не-JSON.
2. Валидация на выходе — доверять модели нельзя даже в JSON-режиме: ключи
   могут быть лишними, значения не того типа. Пропускаем только своё.
3. Fail-open — при любой ошибке возвращаем None, и поиск идёт обычным путём.
   Вспомогательный слой не имеет права ронять основной сценарий.
"""
import json

from config import DEFAULT_GENERATION
from documents import load_json
from generate import complete
from lexical import tokenize

DICHOTOMIES = ("is_extravert", "is_logic", "is_intuitive", "is_rational")

SYSTEM = """Ты разбираешь запросы к справочнику по соционике.

В соционике каждый тип описывается четырьмя признаками (дихотомиями):
- is_extravert: экстраверт (true) или интроверт (false)
- is_logic: логик / мыслительный (true) или этик / чувствующий (false)
- is_intuitive: интуит (true) или сенсорик (false)
- is_rational: рационал / решающий (true) или иррационал / воспринимающий (false)

Соответствие буквам MBTI (запомни точно, здесь легко ошибиться):
  E -> is_extravert true,  I -> is_extravert false
  N -> is_intuitive true,  S -> is_intuitive false
  T -> is_logic true,      F -> is_logic false
  J -> is_rational TRUE (Judging = рационал)
  P -> is_rational FALSE (Perceiving = иррационал)

Твоя задача: определить, задаёт ли пользователь эти признаки, и вернуть JSON.

Правила:
- Верни объект с ключами is_extravert, is_logic, is_intuitive, is_rational.
- Значение true или false, если признак явно назван в запросе.
- Значение null, если про признак ничего не сказано.
- ВАЖНО: если в запросе назван конкретный тип — по имени (Дон Кихот, Габен,
  Цезарь), по коду (ИЛЭ, СЛИ) или четырьмя буквами (ENTP, INFJ) — верни все
  четыре null. Такой запрос ищется по названию напрямую, фильтр только мешает.
- Если запрос про функцию, квадру или отношения — тоже все четыре null.
- Никакого текста вокруг, только JSON.

Примеры:
Запрос: "интуитивный логик экстраверт рационал"
{"is_extravert": true, "is_logic": true, "is_intuitive": true, "is_rational": true}

Запрос: "какой тип сенсорный этик и интроверт"
{"is_extravert": false, "is_logic": false, "is_intuitive": false, "is_rational": null}

Запрос: "кто такой Дон Кихот"
{"is_extravert": null, "is_logic": null, "is_intuitive": null, "is_rational": null}

Запрос: "расскажи про ENTP"
{"is_extravert": null, "is_logic": null, "is_intuitive": null, "is_rational": null}

Запрос: "какие типы иррациональные и логики"
{"is_extravert": null, "is_logic": true, "is_intuitive": null, "is_rational": false}

Запрос: "у кого болевая этика отношений"
{"is_extravert": null, "is_logic": null, "is_intuitive": null, "is_rational": null}"""


def _validate(raw: str) -> dict:
    """Оставляет только известные ключи с булевыми значениями.

    Модель может вернуть лишние поля, строки "true" вместо true или вложенный
    объект. Пропускаем строго своё — это граница доверия между чужим выводом
    и нашей логикой.
    """
    data = json.loads(raw)
    if not isinstance(data, dict):
        return {}
    return {
        key: data[key]
        for key in DICHOTOMIES
        if isinstance(data.get(key), bool)
    }


# Словарь дихотомий. Основы этих слов встречаются и в описательных алиасах
# ("интуитивно-логический экстраверт"), поэтому различать тип по ним нельзя.
DICHOTOMY_VOCABULARY = (
    "интуитивный интуитивно интуит интуиция сенсорный сенсорика сенсорик "
    "логический логика логик логико этический этика этик этико "
    "экстраверт экстравертный интроверт интровертный "
    "рациональный рационал иррациональный иррационал"
)


def _alias_stems() -> set[str]:
    """Основы РАЗЛИЧАЮЩИХ названий типов: имена, псевдонимы, коды.

    Две тонкости.

    Первая: используем тот же стеммер-обрезку, что и BM25 — иначе "Габена"
    не совпадёт с алиасом "Габен". Два места, где текст сравнивается с
    корпусом, обязаны нормализовать его одинаково.

    Вторая: выбрасываем основы слов-дихотомий. Алиас "интуитивно-логический
    экстраверт" целиком состоит из них, и по нему запрос "интуитивный логик
    экстраверт рационал" неотличим от называния типа. Различать может только
    тот токен, которого нет у других смыслов.
    """
    dichotomy_stems = set(tokenize(DICHOTOMY_VOCABULARY))
    stems = set()
    for t in load_json("types.json"):
        for alias in [*t["aliases"], t["name"]]:
            stems.update(tokenize(alias))
    return stems - dichotomy_stems


# Названия слотов Модели А. Если запрос про слот — он про ФУНКЦИЮ типа,
# а не про его дихотомию, и фильтр по дихотомиям тут вреден.
SLOT_VOCABULARY = (
    "базовая программная творческая ролевая болевая мобилизационная "
    "суггестивная активационная референтная ограничительная фоновая "
    "демонстрационная функция"
)


def mentions_function_slot(question: str) -> bool:
    """Спрашивают ли про конкретную функцию в Модели А.

    Зачем отдельная проверка: слова "логика", "этика", "сенсорика", "интуиция"
    обозначают И дихотомию типа, И функцию. Запрос "у кого болевая этика
    отношений" — это вопрос про ЛОГИКОВ (этика у них слабая, потому и болевая),
    но модель видит слово "этика" и фильтрует этиков, исключая правильный ответ.
    Различить это по смыслу модель не может, а по списку слотов — тривиально.
    """
    return bool(set(tokenize(question)) & set(tokenize(SLOT_VOCABULARY)))


def mentions_known_type(question: str) -> bool:
    """Назван ли в запросе конкретный тип.

    Это детерминированная проверка по словарю, а НЕ работа для модели.
    Замер показал: LLM игнорирует прямую инструкцию «верни null, если назван
    тип», и строит фильтр там, где поиск по названию и так даёт 1.00 —
    портя категорию, которая работала идеально. Правило решает это точно
    и бесплатно. Модель нужна там, где есть неоднозначность, а «есть ли в
    строке одно из известных названий» — это поиск по словарю.
    """
    return bool(set(tokenize(question)) & _alias_stems())


def parse_filter(question: str, generation: str = DEFAULT_GENERATION) -> dict | None:
    """Возвращает where-фильтр Chroma или None, если запрос не структурный.

    None означает «фильтровать нечем» — и это нормальный, ожидаемый исход
    для большинства запросов, а не ошибка.
    """
    # Привратник: две детерминированные проверки ДО дорогого и
    # недетерминированного вызова модели. Обе отсекают случаи, где фильтр
    # заведомо не нужен и по замерам только вредит. Заодно экономят 2-5 секунд.
    if mentions_known_type(question) or mentions_function_slot(question):
        return None

    try:
        raw = complete(SYSTEM, f"Запрос: {question}", profile=generation, json_mode=True)
        found = _validate(raw)
    except Exception:
        # Fail-open: разбор запроса — необязательное улучшение. Если он упал
        # (модель недоступна, вернула мусор), поиск обязан продолжить работать.
        return None

    if not found:
        return None
    if len(found) == 1:
        return found
    # Chroma требует $and для нескольких условий сразу
    return {"$and": [{key: value} for key, value in found.items()]}
